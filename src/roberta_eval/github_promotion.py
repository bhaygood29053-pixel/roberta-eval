from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

PROMOTION_VERSION = "roberta_github_defect_proposal/v1"

ROUTES = {
    "provider": "bhaygood29053-pixel/cmis",
    "cmis": "bhaygood29053-pixel/cmis",
    "x1_scout": "bhaygood29053-pixel/roberta-langgraph",
    "roberta": "bhaygood29053-pixel/roberta-langgraph",
    "laboratory": "bhaygood29053-pixel/roberta-eval",
    "runtime_transport": "bhaygood29053-pixel/roberta-langgraph",
    "unknown": None,
}


def _fingerprint(cluster: dict[str, Any]) -> str:
    payload = {
        "cluster_id": cluster["cluster_id"],
        "category": cluster["category"],
        "service": cluster["service"],
        "likely_layer": cluster["likely_layer"],
        "reason": cluster["reason"],
    }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def build_issue_proposal(
    cluster: dict[str, Any],
    *,
    confirmed: bool,
) -> dict[str, Any]:
    if not confirmed:
        raise ValueError("GitHub defect promotion requires confirmed=true")
    if not cluster.get("actionable_product_defect"):
        raise ValueError("cluster is not an actionable product defect")
    if cluster.get("category") in {"EVALUATION_INCOMPLETE", "EVALUATION_ERROR"}:
        raise ValueError("evaluation-system cluster is not promotable")

    layer = str(cluster.get("likely_layer") or "unknown")
    target_repo = ROUTES.get(layer)
    title = (
        f"[ROBERTA Lab] {cluster['severity']} {cluster['service']}: "
        f"{cluster['category']} / {cluster['reason']}"
    )
    member_ids = cluster.get("member_finding_ids", [])
    body_lines = [
        "## Laboratory defect cluster",
        "",
        f"- Cluster: {cluster['cluster_id']}",
        f"- Category: {cluster['category']}",
        f"- Severity: {cluster['severity']}",
        f"- Service: {cluster['service']}",
        f"- Likely layer: {layer}",
        f"- Occurrences: {cluster['occurrence_count']}",
        f"- Reason: {cluster['reason']}",
        "",
        "## Evidence",
        "",
        "Member finding IDs:",
    ]
    body_lines.extend(f"- {value}" for value in member_ids[:25])
    if len(member_ids) > 25:
        body_lines.append(f"- plus {len(member_ids) - 25} more")
    body_lines.extend(
        [
            "",
            "## Required engineering proof",
            "",
            "Reproduce at least one member case, identify the first proven incorrect layer, "
            "fix the underlying defect, then replay the source case plus the permanent "
            "regression case before closing.",
            "",
            "This proposal was generated by ROBERTA Evaluation Laboratory. It is a "
            "reviewable proposal, not proof that an issue was created automatically.",
        ]
    )
    return {
        "proposal_version": PROMOTION_VERSION,
        "proposal_fingerprint": _fingerprint(cluster),
        "cluster_id": cluster["cluster_id"],
        "target_repository": target_repo,
        "routing_status": "routed" if target_repo else "needs_localization",
        "title": title,
        "body": "\n".join(body_lines),
        "labels": ["roberta-lab", "defect", cluster["severity"].lower()],
        "confirmed": True,
        "issue_created": False,
    }


def build_issue_proposals(
    clusters: list[dict[str, Any]],
    *,
    confirmed_cluster_ids: set[str],
) -> list[dict[str, Any]]:
    proposals = [
        build_issue_proposal(
            cluster,
            confirmed=cluster["cluster_id"] in confirmed_cluster_ids,
        )
        for cluster in clusters
        if cluster["cluster_id"] in confirmed_cluster_ids
    ]
    seen: set[str] = set()
    for proposal in proposals:
        fp = proposal["proposal_fingerprint"]
        if fp in seen:
            raise ValueError("duplicate defect proposal fingerprint")
        seen.add(fp)
    return sorted(proposals, key=lambda item: item["proposal_fingerprint"])


def proposal_summary(proposals: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "proposal_version": PROMOTION_VERSION,
        "proposal_count": len(proposals),
        "routed_count": sum(1 for item in proposals if item["routing_status"] == "routed"),
        "needs_localization_count": sum(
            1 for item in proposals if item["routing_status"] == "needs_localization"
        ),
        "issue_created_count": sum(1 for item in proposals if item["issue_created"]),
    }


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def write_proposals(path: Path, proposals: list[dict[str, Any]]) -> None:
    path.write_text(
        "".join(json.dumps(item, sort_keys=True, separators=(",", ":")) + "\n" for item in proposals),
        encoding="utf-8",
    )
